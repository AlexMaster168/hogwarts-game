// Пол героя: выбирается на титульном экране, меняет модель и окончания в репликах, обращённых к игроку.
public static class Gender
{
    public static bool Female;

    static readonly (string m, string f)[] Forms =
    {
        ("Ты новенький", "Ты новенькая"), ("ты новенький", "ты новенькая"), ("Новенький?", "Новенькая?"),
        ("ты раскидал", "ты раскидала"), ("Ты раскидал", "Ты раскидала"), ("ты так научился", "ты так научилась"),
        ("Ты сделал", "Ты сделала"), ("ты годен", "ты годна"), ("Ты справился", "Ты справилась"),
        ("Ты спас", "Ты спасла"), ("ты меня спас", "ты меня спасла"), ("Ты уже доказал", "Ты уже доказала"),
        ("Ты их выпустил", "Ты их выпустила"), ("Ты прошёл путь", "Ты прошла путь"), ("хорошо, что ты пришёл", "хорошо, что ты пришла"), ("Хорошо, что ты пришёл", "Хорошо, что ты пришла"),
    };

    public static string Fix(string s)
    {
        if (!Female || string.IsNullOrEmpty(s)) return s;
        foreach (var (m, f) in Forms) s = s.Replace(m, f);
        return s;
    }
}
